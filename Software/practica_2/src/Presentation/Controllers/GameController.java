package Presentation.Controllers;

import Business.Entities.Generator;
import Business.Entities.GeneratorThread;
import Business.Entities.Upgrade;
import Business.Exceptions.BusinessException;
import Business.Managers.*;
import Presentation.Views.GameView;

import javax.swing.*;
import java.awt.event.ActionEvent;
import java.awt.event.ActionListener;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;


/**
 * GameController class implements the ActionListener interface to handle actions performed
 * in the GameView class, such as clicking buttons.
 */
public class GameController implements ActionListener {

    private final GameView gameView;
    private final MainController mainController;
    private final ShopManager shopManager;
    private final UserManager userManager;
    private final GameManager gameManager;
    private final StatisticsManager statisticsManager;
    private final List<GeneratorThread> generatorThreads;
    private List<Generator> generatorsLoad;
    private List<Upgrade> upgradesLoad;
    private Timer timer;
    private Timer timerStatistics;
    public static final int DELAY = 1000;
    public static final int DELAY_STATISTICS = 1000;

    /**
     * Constructs a new GameController with the specified GameView, MainController, ShopManager, UserManager,
     * GameManager, and StatisticsManager.
     *
     * @param gameView           The GameView associated with this controller.
     * @param shopManager        The ShopManager responsible for shop-related operations.
     * @param mainController     The MainController managing the application flow.
     * @param userManager        The UserManager responsible for user-related operations.
     * @param gameManager        The GameManager responsible for game-related operations.
     * @param statisticsManager  The StatisticsManager responsible for statistics-related operations.
     */
    public GameController(GameView gameView, ShopManager shopManager, MainController mainController, UserManager userManager, GameManager gameManager, StatisticsManager statisticsManager) {
        this.gameView = gameView;
        this.shopManager = shopManager;
        this.mainController = mainController;
        this.userManager = userManager;
        this.gameManager = gameManager;
        this.statisticsManager = statisticsManager;
        this.generatorThreads = new ArrayList<>();
        this.generatorsLoad = new ArrayList<>();
        this.upgradesLoad = new ArrayList<>();

        gameView.setCoffeeButtonsListeners(this);
        gameView.setGeneratorsButtonsListeners(this);
        gameView.setUpgradeButtonsListeners(this);

        startCoffeeCounterUpdater();
        startStatisticsUpdater();
    }

    /**
     * Invoked when an action occurs. Handles the action events generated by buttons in the GameView.
     *
     * @param actionEvent The ActionEvent instance representing the action performed.
     */
    @Override
    public void actionPerformed(ActionEvent actionEvent) {
        String actionCommand = actionEvent.getActionCommand();
        mainController.setCurrentView("game");

        switch (actionCommand) {
            case GameView.GAME_BACk_MENU:
                stopTimer();
                gameManager.stopTimer();
                stopThreadsAndExit();
                try {
                    generatorsLoad = gameManager.getAllGeneratorsByGameId(gameManager.getCurrentGame().getGameId());
                } catch (BusinessException e) {
                    gameView.showMessage(e.getMessage());
                }
                try {
                    upgradesLoad = gameManager.getAllUpgradesByGameId(gameManager.getCurrentGame().getGameId());
                } catch (BusinessException e) {
                    gameView.showMessage(e.getMessage());
                }
                mainController.showMenu();
                try {
                    gameManager.updateGameInDatabase(gameManager.getCurrentGame());
                } catch (BusinessException e) {
                    gameView.showMessage(e.getMessage());
                }
                break;
            case GameView.GAME_ACCOUNT:
                stopTimer();
                gameManager.stopTimer();
                stopThreadsAndExit();
                try {
                    generatorsLoad = gameManager.getAllGeneratorsByGameId(gameManager.getCurrentGame().getGameId());
                } catch (BusinessException e) {
                    gameView.showMessage(e.getMessage());                }
                try {
                    upgradesLoad = gameManager.getAllUpgradesByGameId(gameManager.getCurrentGame().getGameId());
                } catch (BusinessException e) {
                    gameView.showMessage(e.getMessage());                }
                mainController.showAccount();
                try {
                    gameManager.updateGameInDatabase(gameManager.getCurrentGame());
                } catch (BusinessException e) {
                    gameView.showMessage(e.getMessage());                }
                break;
            case GameView.GAME_END_GAME:
                if (gameView.showConfirmEndGame() == JOptionPane.YES_OPTION) {
                    stopTimer();
                    gameManager.stopTimer();
                    stopThreadsAndExit();
                    mainController.showMenu();
                    try {
                        gameManager.deleteGame(gameManager.getCurrentGame().getGameId());
                    } catch (BusinessException e) {
                        gameView.showMessage(e.getMessage());                    }
                }
                break;
            case GameView.GAME_COFFEE:
                gameManager.getCurrentGame().incrementCoffee();
                gameView.updateCoffeeCounter(gameManager.getCurrentGame().getCafesAvailable());
                break;
            case GameView.GAME_BUY_FIRST_GENERATOR:
                try {
                    buyGenerator(0);
                } catch (BusinessException e) {
                    gameView.showMessage(e.getMessage());                }
                break;
            case GameView.GAME_BUY_SECOND_GENERATOR:
                try {
                    buyGenerator(1);
                } catch (BusinessException e) {
                    gameView.showMessage(e.getMessage());                }
                break;
            case GameView.GAME_BUY_THIRD_GENERATOR:
                try {
                    buyGenerator(2);
                } catch (BusinessException e) {
                    gameView.showMessage(e.getMessage());                }
                break;
            case GameView.GAME_UPGRADE_CAVE:
                try {
                    buyUpgrade(0);
                } catch (BusinessException e) {
                    gameView.showMessage(e.getMessage());                }
                break;
            case GameView.GAME_UPGRADE_FARM:
                try {
                    buyUpgrade(1);
                } catch (BusinessException e) {
                    gameView.showMessage(e.getMessage());                }
                break;
            case GameView.GAME_UPGRADE_FACTORY:
                try {
                    buyUpgrade(2);
                } catch (BusinessException e) {
                    gameView.showMessage(e.getMessage());                }
                break;
            default:
                mainController.showMenu();
                break;
        }
    }

    /**
     * Starts the timer for updating the coffee counter and generators' production.
     */
    public void startTimer() {
        timer.start();
        timerStatistics.start();
    }

    /**
     * Stops the timer.
     */
    public void stopTimer() {
        timer.stop();
        timerStatistics.stop();
    }

    /**
     * Starts the timer for updating the coffee counter.
     */
    public void startCoffeeCounterUpdater() {
        timer = new Timer(DELAY, e -> {
            if (gameManager.getCurrentGame() != null) {
                int updatedCoffeeCount = gameManager.getCurrentGame().getCafesAvailable();
                gameView.updateCoffeeCounter(updatedCoffeeCount);
                updateGeneratorsTable();
            }
        });
    }

    /**
     * Starts the timer for updating the statistics.
     */
    public void startStatisticsUpdater() {
        timerStatistics = new Timer(DELAY_STATISTICS, e -> {
            if (gameManager.getCurrentGame() != null) {
                try {
                    statisticsManager.deleteStatistics(userManager.getUserId(), gameManager.getCurrentGame().getGameId(), gameManager.getCurrentGame().getElapsedTimeInMinutes());
                } catch (BusinessException ex) {
                    gameView.showMessage(ex.getMessage());
                }
                try {
                    statisticsManager.initializeStatistics(gameManager.getCurrentGame().getUserId(), userManager.getUsername(),
                            gameManager.getCurrentGame().getGameId(), gameManager.getCurrentGame().getNameGame(),
                            gameManager.getCurrentGame().getCafesAvailable(), gameManager.getCurrentGame().getElapsedTimeInMinutes());
                } catch (BusinessException ex) {
                    gameView.showMessage(ex.getMessage());
                }
                gameManager.calculateElapsedTime();
            }
        });
    }


    /**
     * Updates the generators table in the GameView.
     */
    private void updateGeneratorsTable() {
        Map<String, Integer> generatorCounts = new HashMap<>();
        Map<String, Integer> upgradeCounts = new HashMap<>();
        Map<String, Integer> upgradeProductions = new HashMap<>();
        Map<String, Integer> generatorProductions = new HashMap<>();
        List<Generator> availableGenerators = shopManager.getCurrentShop().getAvailableGenerators();
        List<Upgrade> availableUpgrades = shopManager.getCurrentShop().getAvailableUpgrades();

        // PRODUCTION OF EACH GENERATOR
        for (Upgrade upgrade : availableUpgrades) {
            String upgradeName = upgrade.getUpgradeName();
            int count = gameManager.getCurrentGame().getUpgradeCountByName(upgradeName);
            upgradeCounts.put(upgradeName, count);
            int production = gameManager.getProductionUpgrade(shopManager.getCurrentShop().getUpgradeProductionByName(upgradeName));
            upgradeProductions.put(upgradeName, production);
        }

        for (Generator generator : availableGenerators) {
            String generatorName = generator.getName();
            int count = gameManager.getCurrentGame().getGeneratorCountByName(generatorName);
            generatorCounts.put(generatorName, count);
            int production = gameManager.getProductionGenerator(shopManager.getCurrentShop().getGeneratorProductionByName(generatorName), count, upgradeCounts.getOrDefault(generatorName, 0), upgradeProductions.getOrDefault(generatorName, 0));
            generatorProductions.put(generatorName, production);
        }

        // TOTAL PRODUCTION OF EACH GENERATOR
        Map<String, Integer> totalProductions = new HashMap<>();
        for (String generatorName : generatorCounts.keySet()) {
            int count = generatorCounts.get(generatorName);
            int production = generatorProductions.get(generatorName);
            int totalProduction = gameManager.getTotalProductionGenerator(count, production);
            totalProductions.put(generatorName, totalProduction);
        }

        // TOTAL PERCENTAGE OF EACH GENERATOR
        Map<String, Integer> totalProductionPercentages = new HashMap<>();
        for (String generatorName : generatorCounts.keySet()) {
            int totalProduction = totalProductions.get(generatorName);
            int totalProductionPercentage = gameManager.getTotalProductionPercentageGenerator(totalProduction, totalProductions);
            totalProductionPercentages.put(generatorName, totalProductionPercentage);
        }

        gameView.updateGeneratorsTable(generatorCounts, generatorProductions, totalProductions, totalProductionPercentages);
    }

    /**
     * Buys a generator.
     *
     * @param index The index of the generator to buy.
     */
    private void buyGenerator(int index) throws BusinessException {
        List<Generator> generators = shopManager.getCurrentShop().getAvailableGenerators();

        if (index >= 0 && index < generators.size()) {
            Generator generator = generators.get(index);
            int generatorTypeNumber = gameManager.getCurrentGame().getGeneratorCountByName(generator.getName());
            int generatorCost = (int) (generator.getBaseCost() * Math.pow(generator.getIncrementCost(), generatorTypeNumber));

            if (gameManager.getCurrentGame().getCafesAvailable() >= generatorCost) {
                gameManager.getCurrentGame().setCafesAvailable(gameManager.getCurrentGame().getCafesAvailable() - generatorCost);
                gameManager.getCurrentGame().addGenerator(generator);
                gameManager.insertGameGenerators(gameManager.getCurrentGame().getGameId(), generator.getName());

                GeneratorThread generatorThread = new GeneratorThread(gameManager.getCurrentGame(), generator);
                Thread thread = new Thread(generatorThread);
                thread.start();
                generatorThreads.add(generatorThread);
                int nextGeneratorTypeNumber = generatorTypeNumber + 1;
                int nextGeneratorCost = (int) (generator.getBaseCost() * Math.pow(generator.getIncrementCost(), nextGeneratorTypeNumber));
                gameView.updateGeneratorLabels(generator.getName(), nextGeneratorCost, generator.getBaseProduction(), index);

            } else {
                gameView.showBuyingError();
            }
        } else {
            System.err.println("Generator index out of range");
        }
    }

    /**
     * Buys an upgrade.
     *
     * @param index The index of the upgrade to buy.
     */
    private void buyUpgrade(int index) throws BusinessException {
        List<Upgrade> upgrades = shopManager.getCurrentShop().getAvailableUpgrades();
        Upgrade upgrade = upgrades.get(index);
        int upgradeTypeNumber = gameManager.getCurrentGame().getUpgradeCountByName(upgrade.getUpgradeName());
        int totalCost = upgrade.getCost() + upgrade.getCost() * upgradeTypeNumber;

        if (gameManager.getCurrentGame().getCafesAvailable() >= totalCost) {
            gameManager.getCurrentGame().setCafesAvailable(gameManager.getCurrentGame().getCafesAvailable() - totalCost);
            gameManager.getCurrentGame().addUpgrade(upgrade);
            gameManager.insertGameUpgrades(gameManager.getCurrentGame().getGameId(), upgrade.getUpgradeName());

            int nextUpgradeTypeNumber = upgradeTypeNumber + 1;
            int nextUpgradeCost = upgrade.getCost() + upgrade.getCost() * nextUpgradeTypeNumber;

            gameView.updateUpgradeLabels(upgrade.getUpgradeName(), nextUpgradeCost, upgrade.getProductionMultiplier(), index);
        } else {
            gameView.showBuyingError();
        }
    }

    /**
     * Loads the game from saved state.
     */
    public void loadGame() {
        for (Upgrade upgrade : upgradesLoad) {
            gameManager.getCurrentGame().addUpgrade(upgrade);
        }
        for (Generator generator : generatorsLoad) {
            gameManager.getCurrentGame().addGenerator(generator);

            GeneratorThread generatorThread = new GeneratorThread(gameManager.getCurrentGame(), generator);
            Thread thread = new Thread(generatorThread);
            thread.start();
            generatorThreads.add(generatorThread);
        }
    }

    /**
     * Stops all running threads and clears the thread lists.
     */
    private void stopThreadsAndExit() {
        for (GeneratorThread thread : generatorThreads) {
            thread.stopThread();
        }
        generatorThreads.clear();
    }
}
