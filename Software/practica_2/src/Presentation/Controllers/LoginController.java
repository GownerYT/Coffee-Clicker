package Presentation.Controllers;

import Business.Exceptions.BusinessException;
import Business.Managers.UserManager;
import Presentation.Views.LoginView;

import java.awt.event.ActionEvent;
import java.awt.event.ActionListener;
/**
 * LoginController class implements the ActionListener interface to handle actions performed
 * in the LoginView class, such as clicking buttons.
 */
public class LoginController implements ActionListener {

    private final LoginView loginView;
    private final MainController mainController;
    private final UserManager userManager;

    /**
     * Constructs a new LoginController with the specified LoginView, MainController, and UserManager.
     * @param loginView The LoginView associated with this controller.
     * @param mainController The MainController managing the application flow.
     * @param userManager The UserManager responsible for user-related operations.
     */
    public LoginController(LoginView loginView, MainController mainController, UserManager userManager) {
        this.loginView = loginView;
        this.mainController = mainController;
        this.userManager = userManager;
    }

    /**
     * Invoked when an action occurs. Handles the action events generated by buttons in the LoginView.
     * @param actionEvent The ActionEvent instance representing the action performed.
     */
    @Override
    public void actionPerformed(ActionEvent actionEvent) {
        String actionCommand = actionEvent.getActionCommand();
        String usernameOrEmail = loginView.getUsernameOrEmail();
        String password = loginView.getPassword();

        switch (actionCommand) {
            case LoginView.SCREEN_LOGIN_LOGIN:
                UserManager.Status loginStatus = null;
                try {
                    loginStatus = userManager.loginUser(usernameOrEmail, password);
                } catch (BusinessException e) {
                    loginView.showMessage(e.getMessage());
                }
                if (loginStatus != null) {
                    switch (loginStatus) {
                        case SUCCESS:
                            mainController.showMenu();
                            loginView.clearFields();
                            break;
                        case USER_NOT_FOUND:
                            loginView.showUserNameError();
                            break;
                        case INCORRECT_PASSWORD:
                            loginView.showPasswordError();
                            break;
                    }
                }
                break;
            case LoginView.SCREEN_LOGIN_REGISTER:
                mainController.showRegister();
                break;
            case LoginView.SCREEN_LOGIN_BACK:
            default:
                mainController.showHome();
                break;
        }
    }
}
