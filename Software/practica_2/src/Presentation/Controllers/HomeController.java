package Presentation.Controllers;

import Presentation.Views.HomeView;

import java.awt.event.ActionEvent;
import java.awt.event.ActionListener;
/**
 * HomeController class implements the ActionListener interface to handle actions performed
 * in the HomeView class, such as clicking buttons.
 */
public class HomeController implements ActionListener {

    private final MainController mainController;

    /**
     * Constructs a new HomeController with the specified HomeView and MainController.
     * @param mainController The MainController managing the application flow.
     */
    public HomeController(MainController mainController) {
        this.mainController = mainController;
    }

    /**
     * Invoked when an action occurs. Handles the action events generated by buttons in the HomeView.
     * @param actionEvent The ActionEvent instance representing the action performed.
     */
    @Override
    public void actionPerformed(ActionEvent actionEvent) {
        String actionCommand = actionEvent.getActionCommand();

        switch (actionCommand) {
            case HomeView.HOME_REGISTER:
                mainController.showRegister();
                break;
            case HomeView.HOME_LOGIN:
                mainController.showLogin();
                break;
            default:
                mainController.showHome();
                break;
        }
    }
}
