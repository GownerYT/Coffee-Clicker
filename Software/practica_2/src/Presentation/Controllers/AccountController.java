package Presentation.Controllers;

import Business.Exceptions.BusinessException;
import Business.Managers.GameManager;
import Business.Managers.UserManager;
import Presentation.Views.AccountView;

import java.awt.event.ActionEvent;
import java.awt.event.ActionListener;

/**
 * AccountController class implements the ActionListener interface to handle actions performed
 * in the AccountView class, such as clicking buttons.
 */
public class AccountController implements ActionListener {

    private final AccountView accountView;
    private final MainController mainController;
    private final UserManager userManager;
    private final GameManager gameManager;
    private final GameController gameController;

    /**
     * Constructs a new AccountController with the specified AccountView, MainController, and UserManager.
     * @param accountView The AccountView associated with this controller.
     * @param mainController The MainController managing the application flow.
     * @param userManager The UserManager responsible for user-related operations.
     */
    public AccountController(AccountView accountView, MainController mainController, UserManager userManager, GameManager gameManager, GameController gameController) {
        this.accountView = accountView;
        this.userManager = userManager;
        this.mainController = mainController;
        this.gameManager = gameManager;
        this.gameController = gameController;
    }

    /**
     * Invoked when an action occurs. Handles the action events generated by buttons in the AccountView.
     * @param actionEvent The ActionEvent instance representing the action performed.
     */
    public void actionPerformed(ActionEvent actionEvent) {
        String actionCommand = actionEvent.getActionCommand();

        switch (actionCommand) {
            case AccountView.ACCOUNT_LOGOUT:
                if (accountView.showLogoutAccount()) {
                    userManager.logoutUser();
                    mainController.showHome();
                } else {
                    mainController.showAccount();
                }
                break;
            case AccountView.ACCOUNT_DELETE:
                if (accountView.showDeleteAccount()) {
                    try {
                        userManager.deleteUser();
                    } catch (BusinessException e) {
                        accountView.showMessage(e.getMessage());
                    }
                    mainController.showHome();
                } else {
                    mainController.showAccount();
                }
                break;
            case AccountView.ACCOUNT_CANCEL:
                switch (mainController.getCurrentView()) {
                    case "game":
                        int userId = userManager.getUserId();
                        try {
                            gameManager.initializeGame(gameManager.getGameByUserId(userId).getNameGame(), userId, gameManager.getGameByUserId(userId).getCafesAvailable(), gameManager.getGameByUserId(userId).getElapsedTime());
                        } catch (BusinessException e) {
                            accountView.showMessage(e.getMessage());                        }
                            mainController.showGame();
                            gameController.loadGame();
                            gameManager.startTimer();
                            gameController.startTimer();
                            gameManager.resetAppliedCurrentMinutes();
                        break;
                    case "statistics":
                        mainController.showStatics();
                        break;
                    case "menu":
                    default:
                        mainController.showMenu();
                        break;
                }
                break;
            default:
                mainController.showMenu();
                break;
        }
    }



}
